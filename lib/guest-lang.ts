// sentences with values in them, as patterns: "Pay {}" matches "Pay ₹240"
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const PATTERNS = Object.entries(HI)
  .filter(([k]) => k.includes("{}"))
  .map(([k, v]) => ({ re: new RegExp("^" + k.split("{}").map(esc).join("([\\s\\S]*?)") + "$"), v }));

export function hindi(en: string): string {
  const hit = HI[en];
  if (hit !== undefined) return hit;
  for (const p of PATTERNS) {
    const m = en.match(p.re);
    if (m) {
      let i = 1;
      return p.v.replace(/\{\}/g, () => m[i++] ?? "");
    }
  }
  return en;
}

/** tx(lang, English, मराठी): the guest-screen text in the chosen language. */
export const tx = (lang: GuestLang, en: string, mr: string) => (lang === "mr" ? mr : lang === "hi" ? hindi(en) : en);
